"""
05_vector_stores_chroma.py
==========================
Phase 1: Persistent Vector Database with ChromaDB
IncidentLens Vector Store:
1. Initializes a local persistent ChromaDB client (stored in data/chroma_db/).
2. Creates/loads the collection 'incidentlens_postmortems' with cosine distance space.
3. Indexes all 105 production chunks generated by Module 03.
4. Preserves full metadata (chunk_id, source_file, incident_name, page_number) for source attribution.
5. Implements metadata filtering (e.g. where={"incident_slug": "..."}).
6. Exports `get_incident_collection()` for the end-to-end RAG pipeline (Module 06).
"""

import sys
import os
import warnings
from pathlib import Path
from typing import List, Dict, Any

# Ensure UTF-8 output encoding across Windows shells
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

warnings.filterwarnings("ignore", category=DeprecationWarning)

import chromadb
from chromadb.utils import embedding_functions

# Dynamic import of Module 03 production chunks
import importlib.util

def _get_chunker():
    current_dir = Path(__file__).resolve().parent
    script_path = current_dir / "03_text_splitters.py"
    spec = importlib.util.spec_from_file_location("module_03_splitters", str(script_path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return getattr(mod, "get_production_chunks")

get_production_chunks = _get_chunker()

COLLECTION_NAME = "incidentlens_postmortems"


def get_chroma_path() -> Path:
    """Returns the persistent ChromaDB database directory in data/chroma_db/"""
    root_dir = Path(__file__).resolve().parent.parent
    chroma_dir = root_dir / "data" / "chroma_db"
    chroma_dir.mkdir(parents=True, exist_ok=True)
    return chroma_dir


def get_persistent_client() -> chromadb.PersistentClient:
    """Creates a local PersistentClient storing vectors on disk."""
    return chromadb.PersistentClient(path=str(get_chroma_path()))


def get_incident_collection(client: chromadb.PersistentClient = None):
    """
    Returns the persistent collection configured with cosine space
    and the local all-MiniLM-L6-v2 embedding function.
    """
    if client is None:
        client = get_persistent_client()

    ef = embedding_functions.DefaultEmbeddingFunction()

    return client.get_or_create_collection(
        name=COLLECTION_NAME,
        embedding_function=ef,
        metadata={"hnsw:space": "cosine"}
    )


def index_chunks(collection, chunks: List[Any], batch_size: int = 40):
    """
    Indexes document chunks into ChromaDB with idempotency:
    Extracts text, metadata, and chunk_ids.
    """
    print(f"\n[Indexing] Storing {len(chunks)} chunks into ChromaDB collection '{collection.name}'...")

    total = len(chunks)
    for i in range(0, total, batch_size):
        batch = chunks[i:i + batch_size]

        ids = [doc.metadata["chunk_id"] for doc in batch]
        documents = [doc.page_content for doc in batch]
        metadatas = [
            {
                "source_file": doc.metadata.get("source_file", ""),
                "incident_slug": doc.metadata.get("incident_slug", ""),
                "incident_name": doc.metadata.get("incident_name", ""),
                "file_type": doc.metadata.get("file_type", ""),
                "page_number": int(doc.metadata.get("page_number", 1)),
                "chunk_id": doc.metadata.get("chunk_id", ""),
            }
            for doc in batch
        ]

        # Use upsert to avoid duplicate key errors on repeated runs
        collection.upsert(
            ids=ids,
            documents=documents,
            metadatas=metadatas
        )
        print(f"    Indexed batch {i + 1} to {min(i + batch_size, total)} of {total} chunks")

    print(f"✅ Indexing complete! Collection currently contains {collection.count()} chunks on disk.")


def run_query(collection, query_text: str, n_results: int = 3, where_filter: Dict = None):
    """Queries the ChromaDB collection using vector similarity search."""
    kwargs = {
        "query_texts": [query_text],
        "n_results": n_results
    }
    if where_filter:
        kwargs["where"] = where_filter

    return collection.query(**kwargs)


def print_query_results(results, title: str):
    """Prints formatted query results with cosine distance and metadata citations."""
    print("\n" + "-" * 80)
    print(f" 🔎 {title}")
    print("-" * 80)

    ids = results["ids"][0]
    docs = results["documents"][0]
    metas = results["metadatas"][0]
    distances = results["distances"][0]

    for rank, (chunk_id, doc_text, meta, dist) in enumerate(zip(ids, docs, metas, distances), 1):
        # Convert cosine distance to cosine similarity: Similarity = 1 - Distance
        similarity = 1.0 - dist
        print(f"\n[Rank {rank}] Cosine Similarity: {similarity:.4f} (Distance: {dist:.4f})")
        print(f"    ID:       {chunk_id}")
        print(f"    Incident: {meta.get('incident_name')}")
        print(f"    Source:   {meta.get('source_file')} (Page {meta.get('page_number')})")
        print(f"    Passage:  \"{doc_text.strip()[:200]}...\"")


def main():
    print("=" * 80)
    print(" 💾 IncidentLens — Module 05: Persistent Vector Stores with ChromaDB")
    print("=" * 80)

    # 1. Initialize Persistent Client
    chroma_path = get_chroma_path()
    client = get_persistent_client()
    collection = get_incident_collection(client)
    print(f"[1] Persistent ChromaDB initialized at: {chroma_path}")
    print(f"    Collection: '{collection.name}' (HNSW Cosine Space)")

    # 2. Ingest & Index All Chunks from Module 03
    chunks = get_production_chunks()
    index_chunks(collection, chunks)

    # 3. Test Query A: Global Semantic Retrieval (Unfiltered)
    query_a = "What caused the primary database to diverge and create a split-brain condition?"
    results_a = run_query(collection, query_a, n_results=3)
    print_query_results(results_a, f"Test A: Global Search -> \"{query_a}\"")

    # 4. Test Query B: Metadata-Filtered Retrieval
    # Specifically restricts retrieval to CrowdStrike despite asking about memory failures
    query_b = "What kernel driver triggered the crash and what memory bugcheck occurred?"
    filter_b = {"incident_slug": "crowdstrike_outage_2024"}
    results_b = run_query(collection, query_b, n_results=3, where_filter=filter_b)
    print_query_results(results_b, f"Test B: Metadata-Filtered Search (Incident='Crowdstrike') -> \"{query_b}\"")

    print("\n" + "=" * 80)
    print(" ✅ Module 05 Complete: Vector Store Indexed & Queryable!")
    print(" Next Step: Hook vector retrieval to LLM with LangChain LCEL (Module 06).")
    print("=" * 80)


if __name__ == "__main__":
    main()
