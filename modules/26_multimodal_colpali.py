"""
26_multimodal_colpali.py
========================
Phase 6: Multimodal RAG (ColPali / Vision)
IncidentLens Visual-Evidence Pipeline:

WHY THIS EXISTS:
  Every module before this one reads a post-mortem as TEXT. But a real incident report is
  not only text: the failure story is usually carried by a Grafana CPU/latency spike chart,
  an architecture topology diagram, a flamegraph or a network-flow picture. Those pixels
  contain the numbers ("payments p99 jumped from 180 ms to 4.2 s at 04:09 UTC") that the
  prose only summarises as "latency increased". A text-only RAG pipeline is blind to them.
  Multimodal RAG closes that gap: it extracts the VISUAL elements of the PDF, has a vision
  model describe them in words, embeds those descriptions next to the text chunks, and
  retrieves visual evidence and text evidence in the same query.

  This is the "description" flavour of multimodal RAG (describe image -> embed text of the
  description). ColPali's "late interaction over image patches" is the no-description
  alternative; it needs a multi-vector index and a GPU-class encoder, neither of which the
  free tier provides. Describing the image keeps the index identical to every other module
  (one Chroma collection, one MiniLM embedding function), which is why it was chosen here.

PIPELINE (each numbered section below):
  1. EXTRACT      pypdf `page.images` pulls every embedded image out of the PDF. Each image
                  is written to data/vision_images/, hashed with SHA-256, and DEDUPLICATED by
                  that hash, because a PDF repeats the same logo object on every page.
  2. RENDER       Optional. If PyMuPDF (`fitz`) is importable, full pages are rendered to PNG
                  so that VECTOR graphics (axes, lines, text drawn by the PDF itself, not an
                  embedded raster) become visible to the vision model. NOT INSTALLED here, so
                  this step degrades honestly and says so instead of faking a page image.
  3. DESCRIBE     A vision-capable FREE OpenRouter model (chosen at runtime from /models by
                  input modality, `:free` suffix) describes each unique real image. Images are
                  resized to <=768 px on the longest side first, to keep image tokens small.
                  A 429 backs off and retries; a genuinely unusable model fails over to the
                  next candidate (two candidates are always tried before giving up). If no
                  model accepts an image, the description checks FAIL loudly - a description
                  is never invented.
  4. CHART PROBE  The real corpus contains NO Grafana charts. To prove that visual reading
                  actually happens (and is not a plausible-sounding hallucination), one small
                  SYNTHETIC bar chart is drawn with PIL - 4 labelled bars with printed values -
                  and sent to the same model. The reply is then checked for the labels/values
                  that were drawn. This is the only honest way to demonstrate visual reading
                  on this corpus.
  5. INDEX        Real descriptions and the synthetic chart description go into the Chroma
                  collection `incidentlens_vision` (data/chroma_db) with metadata: source file,
                  page, image hash, kind. Text chunks from the existing text collection can be
                  queried side by side, which is what "retrieve text AND visual context" means.
  6. RETRIEVE     A chart-shaped query is run against the vision collection and must return
                  the synthetic chart entry, proving visual evidence is reachable by search.
  7. CHECKS       PASS/FAIL summary; exit 0 only when the achievable checks pass.

HONESTY NOTE (REQUIRED READING - this is the project's own success criterion):
  docs/12_phase6_advanced_rag.md lists the bar as
      "Multimodal RAG extracts actionable information from Grafana chart images".
  That criterion is NOT MET on this corpus, and this module does not pretend otherwise.
  The CrowdStrike post-mortem PDF (data/postmortems/crowdstrike_outage_2024.pdf) embeds
  exactly TWO unique images, repeated on all 12 pages: a 446x80 CrowdStrike wordmark logo
  and a 949x4 horizontal rule. There is no chart, no diagram, no flamegraph and no
  heatmap - at any resolution, embedded or rendered. So the demonstrated chart reading is
  on a SYNTHETIC chart generated by this script, which proves the vision machinery works
  end to end; it does NOT prove that this corpus carries actionable visual information.
  Status of the project criterion: NOT MET on the real corpus / machinery VERIFIED on a
  synthetic chart. See the Module 26 Summary at the bottom of the run.

WHAT THIS MODULE DOES NOT DO (and will not claim):
  - It does not describe vector-drawn page graphics, because page rendering needs PyMuPDF,
    which is not installed and is not installed by this script.
  - It does not summarise page pixels as if they were a chart. A 949x4 strip is reported as
    a 949x4 strip.
  - It does not use GROQ_API_KEY: Groq hosts no vision model on the free tier.
"""

