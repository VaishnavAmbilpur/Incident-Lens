def _account(model: Any) -> Dict[str, Any]:
    """OpenRouter returns /models objects that differ slightly per model; normalise them."""
    if not isinstance(model, dict):
        return {}
    return {
        "id": str(model.get("id", "")),
        "name": str(model.get("name", model.get("id", ""))),
        "modalities": list(((model.get("architecture") or {}).get("input_modalities")) or []),
        "context": model.get("context_length"),
    }


def fetch_free_vision_models(api_key: str) -> List[Dict[str, Any]]:
    """
    List OpenRouter models and keep only FREE ids that accept an IMAGE input.

    This is done at runtime instead of hardcoding a model id: free model ids are retired
    and renamed often, and a hardcoded id would turn into a mysterious failure.
    """
    request = urllib.request.Request(
        f"{OPENROUTER_BASE_URL}/models",
        headers={"Authorization": f"Bearer {api_key}"},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        payload = json.load(response)

    accounts = [_account(m) for m in payload.get("data", [])]
    vision = [
        a for a in accounts
        if a["id"].endswith(":free") and "image" in [m.lower() for m in a["modalities"]]
    ]
    # Preferred ids first (known to work), then any other free image model.
    preferred_rank = {model_id: i for i, model_id in enumerate(PREFERRED_VISION_MODELS)}
    vision.sort(key=lambda a: (preferred_rank.get(a["id"], 99), a["id"]))
    return vision


def _encode_image(path: Path, max_side: int = MAX_IMAGE_SIDE) -> Tuple[str, str, Tuple[int, int]]:
    """
    Resize an image so its longest side is <= max_side and return (data_uri, mime, size).

    Downscaling is not cosmetic: image tokens scale with pixel count, and the free tier is
    shared with other modules, so a 446x80 logo is sent as-is while a large render would be
    shrunk. PNG keeps text/lines crisp; JPEG is only used when the source was JPEG.
    """
    with Image.open(path) as img:
        img = img.convert("RGB") if img.mode not in ("RGB", "L") else img.copy()
        longest = max(img.width, img.height)
        if longest > max_side:
            scale = max_side / float(longest)
            new_size = (max(1, round(img.width * scale)), max(1, round(img.height * scale)))
            img = img.resize(new_size, Image.LANCZOS)
        buffer = io.BytesIO()
        img.save(buffer, format="PNG")
        raw = buffer.getvalue()
        return (
            "data:image/png;base64," + base64.b64encode(raw).decode("ascii"),
            "image/png",
            (img.width, img.height),
        )


def _is_rate_limit(error: Exception) -> bool:
    message = str(error).lower()
    return "429" in message or "rate limit" in message or "rate-limited" in message


def _is_transient(error: Exception) -> bool:
    """
    True for failures that say nothing about whether the model can see images.

    Observed on the free tier: a reasoning model intermittently answers with an error
    payload whose body has no `choices`, so the SDK raises `'NoneType' object is not
    subscriptable` on the FIRST call and then answers perfectly on the next one. Treating
    that as "this model cannot read images" would abandon a working model and burn the
    budget probing worthless candidates.
    """
    message = str(error).lower()
    return _is_rate_limit(error) or any(
        marker in message
        for marker in ("nonetype", "none is not", "no choices", "empty", "timeout",
                       "timed out", "connection", "502", "503", "504", "provider returned error")
    )


def _extract_text(message: Any) -> str:
    """
    Pull the answer out of a chat message.

    Reasoning models on OpenRouter can put the readable answer in `content` with the
    chain-of-thought in `reasoning`; when a gateway truncates mid-thought, `content` is
    empty and the only usable text is `reasoning`. Both are checked rather than assuming
    `message.content` is always a string.
    """
    if message is None:
        return ""
    content = getattr(message, "content", None)
    if isinstance(content, str) and content.strip():
        return content.strip()
    if isinstance(content, list):
        joined = " ".join(
            part.get("text", "") for part in content if isinstance(part, dict)
        ).strip()
        if joined:
            return joined
    reasoning = getattr(message, "reasoning", None)
    if isinstance(reasoning, str) and reasoning.strip():
        return reasoning.strip()
    return ""


def vision_describe(client: Any, model: str, data_uri: str, prompt: str,
                    max_tokens: int = 320) -> Optional[str]:
    """
    One vision call, retried on 429 AND on transient/empty responses. None = no answer.

    The raw `openai` SDK is used, so the message list is built EXPLICITLY here (text part +
    image_url part). There is no LangChain prompt template in this module and therefore no
    brace-escaping trap; prompts are plain Python strings passed as the user content.
    """
    global VISION_CALLS_USED
    messages = [{
        "role": "user",
        "content": [
            {"type": "text", "text": prompt},
            {"type": "image_url", "image_url": {"url": data_uri}},
        ],
    }]
    for attempt in range(1, VISION_MAX_ATTEMPTS + 1):
        if VISION_CALLS_USED >= MAX_VISION_CALLS:
            print(f"    [budget] vision call budget ({MAX_VISION_CALLS}) exhausted")
            return None
        VISION_CALLS_USED += 1
        try:
            response = client.chat.completions.create(
                model=model, temperature=0.0, max_tokens=max_tokens, messages=messages,
            )
        except Exception as exc:
            retryable = _is_transient(exc) and attempt < VISION_MAX_ATTEMPTS
            tag = "429" if _is_rate_limit(exc) else "transient"
            print(f"    [vision {tag}] {model} attempt {attempt}/{VISION_MAX_ATTEMPTS}: "
                  f"{str(exc)[:90]}" + (" - backing off" if retryable else " - giving up"))
            if not retryable:
                return None
            time.sleep(VISION_BACKOFF_SECONDS * attempt)
            continue

        choices = getattr(response, "choices", None) or []
        text = _extract_text(choices[0].message if choices else None)
        if text:
            return text

        # A 200 response with nothing usable in it is a transient provider failure.
        print(f"    [vision empty] {model} attempt {attempt}/{VISION_MAX_ATTEMPTS}: "
              f"response carried no usable text"
              + (" - retrying" if attempt < VISION_MAX_ATTEMPTS else ""))
        if attempt < VISION_MAX_ATTEMPTS:
            time.sleep(VISION_BACKOFF_SECONDS * attempt)
    return None


def select_vision_model(client: Any, api_key: str, probe_image: Path) -> Tuple[Optional[str], Optional[str]]:
    """
    Pick a vision model by actually sending the synthetic probe image to candidates.

    Model metadata says "image input"; only a real call proves the model, the router and the
    upstream provider all accept an image right now. Returns (model_id, reply) - the reply
    from the probe image is the acceptance test result, so no image call is wasted.
    """
    print("\n" + "=" * 80)
    print(" Step 3 - DESCRIBE: pick a vision model that really accepts an image")
    print("=" * 80)
    try:
        candidates = fetch_free_vision_models(api_key)
    except Exception as exc:
        print(f"  Could not list models from OpenRouter: {exc}")
        return None, None

    print(f"  Free models with image input available: {len(candidates)}")
    for account in candidates[:8]:
        print(f"    - {account['id']}  ctx={account['context']}")

    data_uri, _, size = _encode_image(probe_image)
    print(f"\n  Acceptance test image: {probe_image.name} sent as {size[0]}x{size[1]} PNG")
    print(f"  Each candidate gets up to {VISION_MAX_ATTEMPTS} attempts (free-tier providers")
    print("  intermittently return empty bodies); 429s back off, other rejections move on.")
    print("  Trying candidates in order (metadata claim -> real image call):")

    tried = 0
    for account in candidates:
        model_id = account["id"]
        if tried >= 3:          # keep the shared free-tier budget small
            break
        tried += 1
        print(f"\n  [{tried}] {model_id}")
        reply = vision_describe(client, model_id, data_uri, CHART_PROBE_PROMPT)
        if reply:
            print(f"      ACCEPTED the image. Reply ({len(reply)} chars) kept as the")
            print("      synthetic-chart description for Step 4 (no extra call needed).")
            return model_id, reply
        print("      no usable reply - trying the next candidate")
    return None, None


@dataclass
class RealImageOutcome:
    """What happened to one real embedded image: its record text and its information value."""

    record_text: str
    described: bool          # the vision model answered about this image
    informative: bool        # the answer says the image carries incident information
    reason: str


def _labelled_field(text: str, label: str) -> str:
    """Read one `FIELD: value` line out of a structured model reply."""
    match = re.search(rf"^{re.escape(label)}\s*:\s*(.*)$", text, flags=re.IGNORECASE | re.MULTILINE)
    return match.group(1).strip() if match else ""


def classify_description(reply: str) -> Tuple[bool, str]:
    """
    Decide whether a description claims the image carries VISUAL INCIDENT INFORMATION.

    A letterhead wordmark is a real image and a real description, but it is not evidence
    about the outage. Treating "we described a logo" as "the corpus contains visual
    incident data" would be the exact overclaim this module exists to avoid, so the two are
    separated here: described != informative.

    The check reads the STRUCTURED FIELDS instead of grepping the whole reply, because a
    logo reply legitimately contains the phrase "CHART_READING: NONE" - scanning every word
    would score the word "chart" as proof of a chart.
    """
    text = reply.lower()
    kind = _labelled_field(reply, "KIND").lower()
    chart_reading = _labelled_field(reply, "CHART_READING")
    summary = _labelled_field(reply, "SUMMARY").lower()

    logo_markers = ("logo", "wordmark", "letterhead", "brand", "trademark")
    chart_kinds = ("chart", "graph", "plot", "diagram", "topology", "flamegraph", "heatmap",
                   "screenshot", "dashboard")
    reading_absent = chart_reading.strip().lower() in ("", "none", "n/a", "not applicable",
                                                       "no chart", "n/a - not a chart")
    reading_has_numbers = bool(re.search(r"\d", chart_reading))

    looks_like_logo = any(marker in kind or marker in summary for marker in logo_markers)
    looks_like_chart = (any(marker in kind for marker in chart_kinds)
                        or (not reading_absent and reading_has_numbers)
                        or ("logo" not in text and any(marker in summary for marker in chart_kinds)))

    if looks_like_logo and not looks_like_chart:
        return False, "described, but the model itself reads it as a logo/wordmark - no incident data"
    if looks_like_chart:
        return True, "description reports chart/graph content"
    if "logo" in text or "wordmark" in text:
        return False, "described, but read as a logo/wordmark - no incident data"
    return False, "described, but no chart, diagram or data-bearing element was reported"


def describe_real_images(client: Any, model: str,
                         unique: List[ExtractedImage]) -> Dict[str, RealImageOutcome]:
    """
    Describe the unique REAL images. Honest outcomes only: a description or an explicit note.

    Degenerate images (a 949x4 rule) are never sent: a vision model asked to describe a
    four-pixel-tall strip will produce confident prose about nothing, which is exactly the
    hallucination this module is trying to avoid. They are recorded as non-informative.
    """
    print("\n" + "-" * 80)
    print(" Real images (embedded in the CrowdStrike PDF)")
    print("-" * 80)
    outcomes: Dict[str, RealImageOutcome] = {}
    described = 0
    informative = 0
    for entry in unique:
        if entry.saved_path is None:
            continue
        if entry.is_degenerate:
            note = (f"NOT DESCRIBED BY THE VISION MODEL: a {entry.width}x{entry.height} "
                    f"{entry.fmt} strip repeated on every page. At this aspect ratio the "
                    f"object is a decorative horizontal rule, not a chart or diagram; "
                    f"describing it would be invention, not extraction.")
            outcomes[entry.sha256] = RealImageOutcome(note, False, False, "decorative rule")
            print(f"\n  {entry.saved_path.name}  ({entry.size_label})")
            print(f"    {note}")
            continue
        if described >= MAX_DESCRIBED_REAL_IMAGES:
            outcomes[entry.sha256] = RealImageOutcome(
                "NOT DESCRIBED: real-image vision budget reached.", False, False, "budget")
            continue
        data_uri, _, size = _encode_image(entry.saved_path)
        print(f"\n  {entry.saved_path.name}  ({entry.size_label}) -> sent as {size[0]}x{size[1]}")
        reply = vision_describe(client, model, data_uri, DESCRIBE_PROMPT)
        if reply:
            described += 1
            is_informative, reason = classify_description(reply)
            informative += 1 if is_informative else 0
            outcomes[entry.sha256] = RealImageOutcome(reply, True, is_informative, reason)
            for line in reply.splitlines():
                if line.strip():
                    print(f"    | {line.strip()}")
            print(f"    -> information value: {'DATA-BEARING' if is_informative else 'NOT data-bearing'} ({reason})")
        else:
            outcomes[entry.sha256] = RealImageOutcome(
                "NOT DESCRIBED: the vision model did not answer.", False, False, "no reply")
            print("    no reply - recorded as NOT DESCRIBED (nothing is invented)")
    print(f"\n  Real images the model described : {described}/{len(unique)}")
    print(f"  ...of which carry incident data : {informative}")
    if informative == 0 and described:
        print("  Honest statement: every real image in this PDF is non-informative for incident")
        print("  analysis (letterhead logo / decorative rule). No chart exists to describe.")
    return outcomes


