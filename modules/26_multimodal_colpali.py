def _print_checks(results: Dict[str, Tuple[bool, str]]) -> bool:
    print("\n" + "=" * 80)
    print(" Step 7 - PASS/FAIL CHECKS")
    print("=" * 80)
    width = max(len(name) for name in results)
    all_ok = True
    for name, (ok, detail) in results.items():
        status = "PASS" if ok else "FAIL"
        if not ok:
            all_ok = False
        print(f"  [{status}] {name.ljust(width)}  {detail}")
    return all_ok


