# 6. Retrieve — proof that visual evidence is reachable by search
# =====================================================================
RETRIEVAL_QUERIES = [
    "bar chart of p99 latency spike per service during the outage",
    "Grafana latency spike chart screenshot from the incident dashboard",
]


def retrieval_probe(collection: Any, top_k: int = 3) -> Tuple[bool, List[str]]:
    """
    Query the vision collection with chart-shaped questions.

    The pass condition is the honest one: the synthetic chart entry must come back for a
    chart query, which demonstrates that image-derived text is searchable next to the rest
    of the corpus. A miss is reported as a miss.
    """
    print("\n" + "=" * 80)
    print(" Step 6 - RETRIEVE: is the visual evidence reachable?")
    print("=" * 80)
    chart_hit = False
    report: List[str] = []
    for query in RETRIEVAL_QUERIES:
        print(f"\n  Query: {query!r}")
        result = collection.query(query_texts=[query], n_results=top_k)
        ids = (result.get("ids") or [[]])[0]
        documents = (result.get("documents") or [[]])[0]
        metadatas = (result.get("metadatas") or [[]])[0]
        distances = (result.get("distances") or [[]])[0]
        if not ids:
            print("    -> nothing returned")
            continue
        for rank, doc_id in enumerate(ids, start=1):
            meta = metadatas[rank - 1] if rank - 1 < len(metadatas) else {}
            distance = distances[rank - 1] if rank - 1 < len(distances) else float("nan")
            marker = "  <== SYNTHETIC CHART" if meta.get("kind") == "synthetic_chart" else ""
            print(f"    {rank}. [{meta.get('kind','?')}] {doc_id}  distance={distance:.4f}{marker}")
            snippet = " ".join((documents[rank - 1] or "").split())[:150]
            print(f"       {snippet}...")
            if meta.get("kind") == "synthetic_chart":
                chart_hit = True
        report.append(f"{query} -> top1 kind={metadatas[0].get('kind') if metadatas else 'none'}")
    return chart_hit, report


