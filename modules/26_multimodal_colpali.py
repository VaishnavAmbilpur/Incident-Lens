@dataclass
class ExtractedImage:
    """One EMBEDDED raster object found in the PDF, before deduplication."""

    page: int
    name: str
    data: bytes
    sha256: str
    width: int
    height: int
    fmt: str
    mode: str
    saved_path: Optional[Path] = None

    @property
    def is_degenerate(self) -> bool:
        """True for images too thin/small to carry readable visual information."""
        return min(self.width, self.height) < MIN_DESCRIBABLE_SIDE

    @property
    def size_label(self) -> str:
        return f"{self.width}x{self.height} {self.fmt}/{self.mode}"


def read_pdf_pages(pdf_path: Path) -> List[Any]:
    """Return the raw pypdf page objects (pypdf >= 4 exposes page.images)."""
    from pypdf import PdfReader

    reader = PdfReader(str(pdf_path))
    return list(reader.pages)


def extract_embedded_images(pages: List[Any], out_dir: Path) -> Tuple[List[ExtractedImage], List[ExtractedImage]]:
    """
    Pull every embedded image out of the PDF and deduplicate by SHA-256.

    Returns (all_occurrences, unique_images). `all_occurrences` keeps one entry per
    page/image slot so that repetition can be reported honestly; `unique_images` holds the
    first occurrence of each distinct hash, with `saved_path` set.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    occurrences: List[ExtractedImage] = []
    unique: Dict[str, ExtractedImage] = {}

    for page_number, page in enumerate(pages, start=1):
        try:
            images = list(page.images)
        except Exception as exc:                      # pragma: no cover - defensive
            print(f"  [extract] page {page_number}: pypdf could not list images ({exc})")
            continue
        for image_file in images:
            data = image_file.data
            digest = hashlib.sha256(data).hexdigest()
            try:
                with Image.open(io.BytesIO(data)) as probe:
                    width, height = probe.width, probe.height
                    fmt, mode = probe.format or "?", probe.mode
            except Exception:
                width, height, fmt, mode = 0, 0, "?", "?"
            entry = ExtractedImage(
                page=page_number,
                name=getattr(image_file, "name", "image"),
                data=data,
                sha256=digest,
                width=width,
                height=height,
                fmt=fmt,
                mode=mode,
            )
            occurrences.append(entry)
            if digest not in unique:
                unique[digest] = entry

    # Persist exactly one file per distinct hash.
    ordered = sorted(unique.values(), key=lambda e: (e.page, e.name))
    for entry in ordered:
        suffix = (entry.fmt or "PNG").lower()
        suffix = "jpg" if suffix in ("jpeg", "jpg") else suffix
        target = out_dir / f"page{entry.page:02d}_{Path(entry.name).stem}_{entry.sha256[:12]}.{suffix}"
        target.write_bytes(entry.data)
        entry.saved_path = target

    return occurrences, ordered


