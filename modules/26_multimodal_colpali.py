@dataclass
class VisionRecord:
    """One retrievable visual-evidence record (real image description or probe chart)."""

    doc_id: str
    text: str
    source_file: str
    page: int
    image_hash: str
    kind: str
    extra: Dict[str, Any] = field(default_factory=dict)


def get_vision_collection():
    """
    Persistent collection with the SAME local embedding function as the text collection.

    Cosine space + Chroma's default MiniLM embedder means visual descriptions and text
    chunks live in one comparable vector space, so "retrieve both" needs no second model.
    """
    import chromadb
    from chromadb.utils import embedding_functions

    CHROMA_DIR.mkdir(parents=True, exist_ok=True)
    client = chromadb.PersistentClient(path=str(CHROMA_DIR))
    return client.get_or_create_collection(
        name=VISION_COLLECTION,
        embedding_function=embedding_functions.DefaultEmbeddingFunction(),
        metadata={"hnsw:space": "cosine"},
    )


def index_vision_records(collection: Any, records: List[VisionRecord]) -> int:
    """Upsert visual records. Deterministic ids keep re-runs idempotent."""
    if not records:
        return 0
    collection.upsert(
        ids=[r.doc_id for r in records],
        documents=[r.text for r in records],
        metadatas=[
            {
                "source_file": r.source_file,
                "page": int(r.page),
                "image_hash": r.image_hash,
                "kind": r.kind,
                **{k: v for k, v in r.extra.items() if isinstance(v, (str, int, float, bool))},
            }
            for r in records
        ],
    )
    return len(records)


