# Values drawn into the probe image. The description is checked against these strings.
CHART_TITLE = "Synthetic probe: p99 latency by service"
CHART_SERIES: List[Tuple[str, int]] = [
    ("api-gateway", 42),
    ("checkout", 78),
    ("payments", 95),
    ("search", 23),
]


def build_synthetic_chart(path: Path) -> Path:
    """
    Draw one small bar chart with PIL: white canvas, axes, 4 labelled bars, printed values.

    This is not a decoration. It is the control experiment for the whole module: the labels
    and numbers below exist only in these pixels, so if the vision model reports them, it
    genuinely read the image. If it reports other numbers, it hallucinated, and the check
    fails.
    """
    width, height = 520, 340
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)

    left, bottom, top = 70, height - 55, 45
    draw.line([(left, top - 10), (left, bottom)], fill="black", width=2)
    draw.line([(left, bottom), (width - 25, bottom)], fill="black", width=2)
    draw.text((left, 18), CHART_TITLE, fill="black")
    draw.text((14, top - 6), "p99 ms", fill="black")

    span = bottom - (top + 12)
    bar_width = 62
    for index, (label, value) in enumerate(CHART_SERIES):
        x0 = left + 28 + index * 100
        x1 = x0 + bar_width
        y0 = bottom - int(span * value / 100.0)
        draw.rectangle([x0, y0, x1, bottom], fill=(38, 92, 200), outline="black")
        draw.text((x0 + 16, y0 - 16), str(value), fill="black")     # printed value label
        draw.text((x0 - 4, bottom + 10), label, fill="black")        # bar label
        draw.text((x0, bottom + 26), "ms", fill=(90, 90, 90))

    image.save(path, format="PNG")
    return path


def verify_chart_reading(reply: str) -> List[str]:
    """Return the drawn labels/values that actually appear in the model's description."""
    haystack = reply.lower()
    hits: List[str] = []
    for label, value in CHART_SERIES:
        if label.lower() in haystack:
            hits.append(label)
        if re.search(rf"(?<!\d){value}(?!\d)", haystack):
            hits.append(str(value))
    return hits


